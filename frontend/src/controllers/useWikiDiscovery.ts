import { useEffect, useRef, useState } from 'react';
import { errorMessage } from '../repositories/http';
import { isIndexPending, wikiDiscoveryService as service } from '../services/wikiDiscoveryService';
import type { WikiDraft } from '../types/wiki';
import type { WikiAlternative, WikiIndexStatus, WikiSearchResult } from '../types/wikiDiscovery';

export function useWikiDiscovery(id: string, version: number) {
  const [index, setIndex] = useState<WikiIndexStatus | null>(null), [alternatives, setAlternatives] = useState<WikiAlternative[]>([]);
  const [error, setError] = useState(''), [busy, setBusy] = useState(false), [refresh, setRefresh] = useState(0);
  const lifetime = useRef<AbortController | null>(null);
  useEffect(() => {
    const abort = new AbortController(); lifetime.current = abort;
    let timer: ReturnType<typeof setTimeout> | undefined;
    setIndex(null); setAlternatives([]); setError(''); setBusy(false);
    void service.alternatives(id, abort.signal).then(items => {if (!abort.signal.aborted) setAlternatives(items);})
      .catch(e => {if (!abort.signal.aborted) setError(errorMessage(e));});
    async function poll() {
      try {const value = await service.index(id, abort.signal); if (abort.signal.aborted) return;
        setIndex(value); if (isIndexPending(value.status)) timer = setTimeout(() => void poll(), 2500);
      } catch (e) {if (!abort.signal.aborted) setError(errorMessage(e));}
    }
    void poll();
    return () => {abort.abort(); clearTimeout(timer);};
  }, [id, version, refresh]);
  async function retry() {
    const abort = lifetime.current; if (busy || !abort || abort.signal.aborted) return;
    setBusy(true); setError('');
    try {await service.retryIndex(id, version, abort.signal); if (!abort.signal.aborted) setRefresh(n => n + 1);}
    catch (e) {if (!abort.signal.aborted) setError(errorMessage(e));}
    finally {if (!abort.signal.aborted) setBusy(false);}
  }
  return {index, alternatives, error, busy, retry, refresh: () => setRefresh(n => n + 1)};
}

/** Search requests are explicit, never generated by every keystroke or a document view. */
export function useWikiSearch(draft?: WikiDraft, exclude?: string) {
  const [query, setQuery] = useState(''), [result, setResult] = useState<WikiSearchResult | null>(null);
  const [error, setError] = useState(''), [busy, setBusy] = useState(false);
  const active = useRef<AbortController | null>(null);
  useEffect(() => {active.current?.abort(); setResult(null); setError(''); setBusy(false);
    return () => active.current?.abort();
  }, [draft?.title, draft?.markdown, exclude, query]);
  async function run() {
    active.current?.abort(); const abort = new AbortController(); active.current = abort;
    setBusy(true); setError(''); setResult(null);
    try {
      const value = draft ? await service.similar(draft, exclude, abort.signal) : await service.search(query, abort.signal);
      if (!abort.signal.aborted) setResult(value);
    } catch (e) {if (!abort.signal.aborted) setError(errorMessage(e));}
    finally {if (!abort.signal.aborted) setBusy(false);}
  }
  return {query, setQuery, result, error, busy, run};
}
